// Generates lib/generated/image-meta.ts: width, height and a tiny blur placeholder for each photo.
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const files = [
  "hero-long-hair.jpg",
  "salon-hours.jpg",
  "barber-tools.jpg",
  "work-waves.jpg",
  "work-copper.jpg",
  "work-red.jpg",
  "work-highlights.jpg",
  "logo-ig.png",
];

const meta = {};
for (const f of files) {
  const img = sharp(`public/images/${f}`);
  const { width, height } = await img.metadata();
  const buf = await img.resize(12).jpeg({ quality: 40 }).toBuffer();
  meta[f] = { width, height, blur: `data:image/jpeg;base64,${buf.toString("base64")}` };
}

const out = `// Generated by scripts/optimize-images.mjs. Do not edit by hand.
export interface ImageMeta { width: number; height: number; blur: string }
export const imageMeta: Record<string, ImageMeta> = ${JSON.stringify(meta, null, 2)};
`;
writeFileSync("lib/generated/image-meta.ts", out);
console.log("wrote lib/generated/image-meta.ts");
